"""Generate the Rust catalog from the build 147219 operator specification."""
import argparse
import csv
import json
import re
from pathlib import Path


def generate(source, crate):
    layouts = json.loads((source / "layouts.json").read_text(encoding="utf-8"))
    if layouts["metadata"]["build"] != 147219:
        raise ValueError("expected Android build 147219")
    with (source / "protocol.csv").open(encoding="utf-8-sig", newline="") as stream:
        rows = sorted(csv.DictReader(stream), key=lambda row: int(row["opcode_hex"], 16))
    names = {int(value, 16): name for name, value in re.findall(
        r"^    (\w+) = (0x[0-9a-f]+),$", (crate / "opcode.rs").read_text(), re.M)}
    directions = {"BIDIR": "Bidirectional", "C->S": "ClientToServer",
                  "S->C": "ServerToClient", "RESERVED": "Reserved"}
    types = {"u32": "U32", "i32": "I32", "f32": "F32", "u8": "U8", "u16": "U16",
             "f16": "F16", "ascii_z": "Text", "bytes": "Bytes"}
    sizes = {"u32": 4, "i32": 4, "f32": 4, "u8": 1, "u16": 2, "f16": 2}
    lines = ["// Generated by tools/import_protocol_spec.py from Android build 147219.",
             "use super::*;", "use FieldType::*;", "", "#[rustfmt::skip]",
             "pub static CATALOG: &[Entry] = &["]
    seen = set()
    for row in rows:
        key = row["opcode_hex"]
        opcode = int(key, 16)
        if opcode in seen:
            raise ValueError(f"duplicate opcode {key}")
        seen.add(opcode)
        label = json.dumps(row["name"])
        lines.append(f'    Entry {{ opcode: Opcode::{names[opcode]}, name: {label}, '
                     f'direction: Direction::{directions[row["direction"]]}, '
                     f'phase: Phase::{row["phase"].title()},')
        spec = layouts["messages"].get(key)
        if spec is None:
            lines.append("        layout: None },")
            continue
        size = spec["native_body_len"]
        lines.append(f"        layout: Some(Layout {{ body_bytes: {size}, fields: &[")
        end = 0
        for f in spec["fields"]:
            kind, width, offset = f["type"], f["width"], f["offset"]
            if not end <= offset <= size - width or sizes.get(kind, width) != width:
                raise ValueError(f"invalid field in {key}: {f}")
            end = offset + width
            wire_type = types[kind]
            if f.get("endian") == "LE":
                if kind != "u32":
                    raise ValueError(f"unhandled little-endian field in {key}")
                wire_type = "U32Le"
            lines.append(f'            Field::new({json.dumps(f["name"])}, {offset}, {width}, {wire_type}),')
        lines.append("        ] }) },")
    if seen != set(names) or not {int(k, 16) for k in layouts["messages"]} <= seen:
        raise ValueError("opcode enum and specification disagree")
    return "\n".join([*lines, "];", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("protocol_spec", type=Path)
    args = parser.parse_args()
    crate = Path(__file__).resolve().parents[1] / "crates/protocol/src"
    (crate / "spec/catalog.rs").write_text(generate(args.protocol_spec, crate),
                                           encoding="utf-8", newline="\n")
